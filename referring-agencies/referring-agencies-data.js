function buildAccordion(filter) {
  const accordion = document.getElementById('accordion');
  accordion.innerHTML = '';
  let totalVisible = 0;
  const q = (filter || '').toLowerCase().trim();

  data.forEach((reg) => {
    const matchingAgencies = reg.agencies.filter(a =>
      !q ||
      a.city.toLowerCase().includes(q) ||
      a.name.toLowerCase().includes(q) ||
      reg.region.toLowerCase().includes(q)
    );

    if (q && matchingAgencies.length === 0) return;

    totalVisible += matchingAgencies.length;
    const forceOpen = q && matchingAgencies.length > 0;

    const div = document.createElement('div');
    div.className = 'region';

    const header = document.createElement('div');
    header.className = 'region-header' + (forceOpen ? ' open' : '');
    header.innerHTML = `<span class="region-name">${reg.region}</span><span class="region-count">${matchingAgencies.length}</span><svg class="chevron" viewBox="0 0 24 24"><polyline points="6 9 12 15 18 9"/></svg>`;

    const body = document.createElement('div');
    body.className = 'region-body' + (forceOpen ? ' open' : '');

    matchingAgencies.forEach(a => {
      const row = document.createElement('div');
      row.className = 'agency';
      const cityHl = q ? highlight(a.city, q) : a.city;
      const nameHl = q ? highlight(a.name, q) : a.name;

      let links = `<a href="${a.url}" target="_blank" rel="noopener">${nameHl}</a>`;
      if (a.alternate_url) {
        links += ` <a href="${a.alternate_url}" target="_blank" rel="noopener" aria-label="Alternate website for ${escapeHtml(a.name)}" class="agency-alt-link">Alternate site</a>`;
      }

      row.innerHTML = `<span class="agency-city">${cityHl}</span><span class="agency-name">${links}</span>`;
      body.appendChild(row);
    });

    header.addEventListener('click', () => {
      header.classList.toggle('open');
      body.classList.toggle('open');
    });

    div.appendChild(header);
    div.appendChild(body);
    accordion.appendChild(div);
  });

  document.getElementById('resultCount').textContent =
    q ? `${totalVisible} result${totalVisible !== 1 ? 's' : ''}` : `${totalVisible} agencies`;
}

function escapeHtml(text) {
  return text.replace(/[&<>"']/g, function (char) {
    return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#039;'}[char];
  });
}

function highlight(text, q) {
  const idx = text.toLowerCase().indexOf(q);
  return idx === -1
    ? text
    : text.slice(0, idx) + '<mark>' + text.slice(idx, idx + q.length) + '</mark>' + text.slice(idx + q.length);
}

function expandAll() {
  document.querySelectorAll('.region-header').forEach(h => h.classList.add('open'));
  document.querySelectorAll('.region-body').forEach(b => b.classList.add('open'));
}

function collapseAll() {
  document.querySelectorAll('.region-header').forEach(h => h.classList.remove('open'));
  document.querySelectorAll('.region-body').forEach(b => b.classList.remove('open'));
}

function clearSearch() {
  document.getElementById('searchInput').value = '';
  buildAccordion('');
}

document.getElementById('searchInput').addEventListener('input', function() {
  buildAccordion(this.value);
});

